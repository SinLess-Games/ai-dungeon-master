CREATE TABLE `dnd35_character_creation_progress` (
  `character_id` text PRIMARY KEY NOT NULL,
  `skills_finalized` integer DEFAULT false NOT NULL,
  `feats_finalized` integer DEFAULT false NOT NULL,
  `languages_finalized` integer DEFAULT false NOT NULL,
  `wealth_finalized` integer DEFAULT false NOT NULL,
  `equipment_finalized` integer DEFAULT false NOT NULL,
  `spells_finalized` integer DEFAULT false NOT NULL,
  `powers_finalized` integer DEFAULT false NOT NULL,
  `divine_finalized` integer DEFAULT false NOT NULL,
  `companions_finalized` integer DEFAULT false NOT NULL,
  `class_choices_finalized` integer DEFAULT false NOT NULL,
  `created_at` integer DEFAULT (unixepoch()) NOT NULL,
  `updated_at` integer DEFAULT (unixepoch()) NOT NULL,
  FOREIGN KEY (`character_id`) REFERENCES `dnd35_characters`(`character_id`) ON UPDATE no action ON DELETE cascade,
  CONSTRAINT `dnd35_character_creation_progress_skills_bool` CHECK(`skills_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_feats_bool` CHECK(`feats_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_languages_bool` CHECK(`languages_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_wealth_bool` CHECK(`wealth_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_equipment_bool` CHECK(`equipment_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_spells_bool` CHECK(`spells_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_powers_bool` CHECK(`powers_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_divine_bool` CHECK(`divine_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_companions_bool` CHECK(`companions_finalized` in (0,1)),
  CONSTRAINT `dnd35_character_creation_progress_class_choices_bool` CHECK(`class_choices_finalized` in (0,1))
);
