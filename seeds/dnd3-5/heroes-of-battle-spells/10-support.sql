INSERT OR IGNORE INTO dnd35_spell_components (id,spell_id,code,alternative_group,description,cost_copper,xp_cost,is_consumed)
SELECT 'hob-spell-component-'||d.spell_slug||'-'||lower(d.code)||CASE WHEN d.alternative_group='' THEN '' ELSE '-'||replace(d.alternative_group,'-','_') END,
       sp.id,d.code,d.alternative_group,NULL,NULL,NULL,CASE WHEN d.code='M' THEN 1 ELSE 0 END
FROM desired d JOIN dnd35_spells sp ON sp.slug=d.spell_slug AND sp.source_id='hob-3.5' AND sp.owner_user_id IS NULL;
