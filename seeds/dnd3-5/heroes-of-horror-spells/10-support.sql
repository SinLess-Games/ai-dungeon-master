SELECT 'hoh-spell-component-'||d.spell_slug||'-'||lower(d.code)||CASE WHEN d.alternative_group='' THEN '' ELSE '-'||replace(d.alternative_group,'-','_') END,
       sp.id,d.code,d.alternative_group,
       CASE WHEN d.spell_slug='vile-death' AND d.code='M' THEN 'Brimstone and a bloodstone worth at least 500 gp.'
            WHEN d.spell_slug='vile-death' AND d.code='XP' THEN '100 XP.'
            WHEN d.spell_slug='bestow-wound' AND d.code='M' THEN 'Small eye agate worth at least 10 gp.'
            ELSE NULL END,
       CASE WHEN d.spell_slug='vile-death' AND d.code='M' THEN 50000 WHEN d.spell_slug='bestow-wound' AND d.code='M' THEN 1000 ELSE NULL END,
       CASE WHEN d.spell_slug='vile-death' AND d.code='XP' THEN 100 ELSE NULL END,
       CASE WHEN d.code='M' THEN 1 ELSE 0 END
FROM desired d JOIN dnd35_spells sp ON sp.slug=d.spell_slug AND sp.source_id='hoh-3.5' AND sp.owner_user_id IS NULL;

