INSERT INTO dnd35_races
  (id,source_id,source_page,slug,name,description,rules_text,is_homebrew,owner_user_id,is_enabled,
   creature_type_id,favored_class_id,favored_class_rule,size,base_speed_feet,level_adjustment,
   racial_hit_dice,racial_hit_die,natural_armor,bonus_skill_points_per_level,bonus_feats_at_first_level)
SELECT
  'userlist-race-'||d.slug,
  s.id,
  NULL,
  d.slug,
  d.name,
  'Playable-race catalog placeholder from the user-provided by-book index.',
  'Mechanics pending source-backed materialization.',
  0,NULL,0,NULL,NULL,'none','medium',0,
  (SELECT e.level_adjustment
     FROM dnd35_races e
    WHERE e.slug=d.slug AND e.owner_user_id IS NULL AND e.level_adjustment IS NOT NULL
    ORDER BY e.is_enabled DESC, e.created_at ASC
    LIMIT 1),
  0,NULL,0,0,0
FROM desired d
JOIN dnd35_sources s
  ON s.slug=d.source_slug AND s.owner_user_id IS NULL
WHERE NOT EXISTS (
  SELECT 1
  FROM dnd35_races r
  WHERE r.slug=d.slug
    AND r.owner_user_id IS NULL
    AND (r.is_enabled=1 OR r.id LIKE 'userlist-race-%' OR r.source_id=s.id)
);
